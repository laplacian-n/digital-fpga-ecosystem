/* ---- params: defaults, ranges ---- */
/* a part's own settings may also come nested — {kind, params:{format:"mm.ss", down:true}} (lab 7: they
   were dropped and the default 00-99 counter was drawn without a word) */
function partArgs(a){ return a && a.params && typeof a.params==="object" ? Object.assign({}, a, a.params) : (a||{}); }
const PART_GENERIC=new Set(["kind","part","type","module","sheet","name","bus","replace","params","x","y","top","pins","label","id","_check","generator"]);
/* settings this part does not have are refused, naming the ones it has (MCP entry points) */
function partCheckArgs(kind, a){
  const P=PARTS[kind]; if(!P) return;
  const own=Object.keys(P.params||{}), bad=Object.keys(partArgs(a)).filter(k=>!own.includes(k) && !PART_GENERIC.has(k));
  if(bad.length) mcpFail(`${kind} has no setting ${bad.map(k=>"'"+k+"'").join(", ")}`,
    own.length ? `${kind} takes: ${own.map(k=>k+"="+JSON.stringify(P.params[k].def)+(P.params[k].options?" ("+P.params[k].options.join("|")+")":"")).join(", ")}` : `${kind} has no settings`);
}
function partParams(kind, a){
  const P=PARTS[kind]; const out={}; a=partArgs(a);
  Object.entries(P.params||{}).forEach(([k,s])=>{
    let v=a[k]!=null?a[k]:s.def;
    if(s.bool) v=v===true||v==="true"||v===1;
    else if(s.options){ v=typeof s.def==="number"?+v:String(v); if(!s.options.includes(v)) mcpFail(`${kind}.${k} must be one of ${s.options.join(", ")}`); }
    else { v=Math.floor(+v); if(!(v>=s.min && v<=s.max)) mcpFail(`${kind}.${k} must be ${s.min}..${s.max}`); }
    out[k]=v; });
  return out;
}

/* ---- the check: the drawn sheet against the part's reference ---- */
function partPortMap(sch){      // base → [{name, bit|null, width}] for every IN/OUT on the sheet
  const m={in:{}, out:{}};
  sch.components.filter(c=>c.type==="IN"||c.type==="OUT").forEach(c=>{
    const nm=String(c.params.name), w=Math.max(1,+(c.params.width||1)), side=c.type==="IN"?"in":"out";
    const mm=/^(.*?[A-Za-z_])(\d+)$/.exec(nm);
    const add=(base,bit)=>{ (m[side][base]=m[side][base]||[]).push({name:nm, bit, width:w}); };
    if(w>1) add(nm,null); else if(mm) { add(mm[1], +mm[2]); add(nm, null); } else add(nm, null);
  });
  return m;
}
function partVerifyComb(sch, part, p){
  const ports=part.ports(p), pm=partPortMap(sch);
  const ins=Object.entries(ports.in), outs=Object.entries(ports.out).filter(([,w])=>w>0);
  const total=ins.reduce((n,[,w])=>n+w,0);
  // sheet inputs for part-level values: a bus port takes the value, per-bit ports their bit
  const drive=v=>{ const o={}; ins.forEach(([b,w])=>{ const L=pm.in[b]||[];
      const bus=L.find(x=>x.bit==null && x.width>1) || (w===1 && L.find(x=>x.bit==null));
      if(bus) o[bus.name]=v[b]; else L.filter(x=>x.bit!=null).forEach(x=>o[x.name]=ptBits(v[b], x.bit)); }); return o; };
  const read=(got,b,w)=>{ const L=pm.out[b]||[]; const bus=L.find(x=>x.bit==null && (x.width>1 || w===1));
      const num=x=>typeof x==="string" ? parseInt(x,2) : (x==="undriven"?NaN:+x);
      if(bus) return num(got[bus.name]);
      let s=0; for(const x of L.filter(y=>y.bit!=null)){ const bv=num(got[x.name]); if(isNaN(bv)) return NaN; s|=bv<<x.bit; } return s; };
  const fs=flattenSchematic(sch).sch, st=probeStruct(fs);
  const vectors=[];
  if(total<=10){ for(let r=0;r<(1<<total);r++){ let k=0; const v={}; ins.forEach(([b,w])=>{ v[b]=(r>>k)&((1<<w)-1); k+=w; }); vectors.push(v); } }
  else { let seed=12345; const rnd=()=>{ seed=(Math.imul(seed,1103515245)+12345)>>>0; return seed; };
    const corner=[0,1]; for(const cz of corner) vectors.push(Object.fromEntries(ins.map(([b,w])=>[b, cz?((1<<w)-1):0])));
    for(let i=0;i<300;i++) vectors.push(Object.fromEntries(ins.map(([b,w])=>[b, rnd()&((1<<w)-1)]))); }
  let bad=null;
  for(const v of vectors){
    const want=part.ref(v,p); if(!want) continue;                     // a don't-care row (BCD 10–15)
    const got=mcpEvalOuts(sch, fs, st, drive(v));
    for(const [b,w] of outs){ if(want[b]==null) continue; const g=read(got,b,w);
      if(g!==want[b]){ bad={inputs:v, output:b, want:want[b], got:g}; break; } }
    if(bad) break;
  }
  return {pass:!bad, method: total<=10 ? `ทุกแถว (${vectors.length} แถว)` : `${vectors.length} ชุดอินพุต (มุม + สุ่ม)`, mismatch:bad||undefined};
}
function partVerifySeq(sch, part, p){
  const S=part.seq(p), ports=part.ports(p), pm=partPortMap(sch);
  if(S.small) return {pass:false, method:"—", mismatch:{reason:"too many clocks to run one by one — check a copy built at "+JSON.stringify(S.small)}};
  const ins=sch.components.filter(c=>c.type==="IN");
  const byName=n=>ins.find(c=>c.params.name===n);
  const holdAt=i=>{ const v=S.drive(i)||{}, o={};
    Object.entries(v).forEach(([b,val])=>{ const L=pm.in[b]||[]; const bus=L.find(x=>x.bit==null && (x.width>1 || (ports.in[b]||1)===1));
      if(bus){ const c=byName(bus.name); if(c) o[c.id]=val; }
      else L.filter(x=>x.bit!=null).forEach(x=>{ const c=byName(x.name); if(c) o[c.id]=ptBits(val,x.bit); }); });
    return o; };
  const j=clientSeqSim(sch, S.cycles, {holdAt, hold:holdAt(0)});
  if(!j.ok) return {pass:false, method:"จำลองไม่ได้", mismatch:{reason:j.reason}};
  const sq=j.sequence, outNames=sq.outputs;
  const val=(row,b)=>{ const L=pm.out[b]||[]; const bus=L.find(x=>x.bit==null && (x.width>1 || (ports.out[b]||1)===1));
    const at=n=>{ const k=outNames.indexOf(n); return k<0?NaN:(row[4]?row[4][k]:row[3][k]); };
    if(bus) return at(bus.name);
    let s=0; for(const x of L.filter(y=>y.bit!=null)) s|=(at(x.name)?1:0)<<x.bit; return s; };
  let s=S.init, bad=null;
  for(let i=0;i<sq.rows.length && !bad;i++){
    const r=S.step(s, S.drive(i)||{});
    for(const [b,want] of Object.entries(r.out)){ const g=val(sq.rows[i], b); if(g!==want){ bad={cycle:i, output:b, want, got:g}; break; } }
    s=r.state;
  }
  return {pass:!bad, method:`${sq.rows.length} clock เทียบกับโมเดลสถานะ`, mismatch:bad||undefined};
}
/* draw a part on a new sheet, check it; returns {sch, verify, intent} — throws (and removes the sheet) if the check fails */
function partBuild(kind, a){
  const part=PARTS[kind]; if(!part) mcpFail(`unknown part '${kind}'`, "list_parts shows them: "+Object.keys(PARTS).join(", "));
  const p=partParams(kind, a||{});
  let it=part.build(p); if(it && it.W) it={module:it.module, components:it.components, nets:it.nets};
  const bits=it.bits;
  it.module=sanId(a.name||it.module||kind);
  // the throw-away copy a big part is checked on needs connections, not routed wires (20 s for lab 6's top)
  const dr=a._check ? drawIntent(it, {noRoute:true}) : aiDrawIntent(it);
  if(!dr||!dr.ok) mcpFail("could not draw the part: "+((dr&&(dr.error||(dr.errors||[]).map(e=>e.msg||e).join("; ")))||"?"));
  const sch=dr.sch;
  if(part.after) part.after(sch, p, Object.assign({bits}, it));
  // the block's pins in the part's own order (a3..a0, b3..b0, cin | s3..s0, cout; 7-seg a..g), not the layout's
  const ports=part.ports(p);
  const order=side=>{ const bases=Object.keys(ports[side]);
    const key=n=>{ const m=/^(.*?[A-Za-z_])(\d+)$/.exec(n), base=m&&bases.includes(m[1])?m[1]:n, bi=bases.indexOf(base);
      return [bi<0?99:bi, base!==n?-(+m[2]):0]; };
    return sch.components.filter(c=>c.type===(side==="in"?"IN":"OUT")).map(c=>String(c.params.name))
      .sort((x,y)=>{ const A=key(x), B=key(y); return (A[0]-B[0])||(A[1]-B[1]); }); };
  sch.portOrder={in:order("in"), out:order("out")};
  if(a.bus){ const was=sch.locked; sch.locked=false; busifyPorts(sch, a.bus); sch.locked=was; }
  // a big divider cannot be run clock by clock: its generator is checked on a small N instead
  let v;
  if(part.seq){ const S=part.seq(p);
    if(S.small){ const sp=typeof S.small==="object"?S.small:{n:S.small}, had=new Set(Object.keys(state.project.schematics));
      const tmp=partBuild(kind, Object.assign({}, a, sp, {name:"__chk", bus:false, _check:true}));
      // the check copy and any sub-sheet only it needed (a small divider) go again
      Object.keys(state.project.schematics).forEach(id=>{ if(!had.has(id)) delete state.project.schematics[id]; });
      state.openTabs=(state.openTabs||[]).filter(i=>state.project.schematics[i]);
      v=Object.assign({}, tmp.verify, {method:`ตัวสร้างเดียวกันที่ ${Object.entries(sp).map(([k,x])=>(k==="n"?"N":k)+"="+x).join(", ")}: `+tmp.verify.method}); }
    else v=partVerifySeq(sch, part, p); }
  else v=partVerifyComb(sch, part, p);
  if(!v.pass){ delete state.project.schematics[sch.id]; state.openTabs=(state.openTabs||[]).filter(i=>i!==sch.id); renderAll();
    mcpFail(`internal check failed for ${kind}: `+JSON.stringify(v.mismatch), "this is a bug in the part library — please report it"); }
  sheetVerifyStamp(sch, `part ${kind} ${JSON.stringify(p)} — ${v.method}`);
  return {sch, verify:v, params:p};
}

