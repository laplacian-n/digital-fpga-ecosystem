/* ===== 22. A library of parts that PROVE themselves (build_part / list_parts) =====================
   From testing the local agent: a 4B model wrote the full adder's equations right, then typed the
   truth table wrong (sum "00001110"), built it, "verified" it against the same wrong columns and
   saved it to the module library. Small models are good at choosing and connecting parts, bad at
   producing bits. So the parts come from here: each kind is generated by code AND checked against
   a reference model (every row when the inputs allow, else ~300 vectors incl. the corners; for
   sequential parts, a clock-by-clock run against a state model) before it is handed over. A part
   that fails its own check is never drawn. The sheet is stamped verified (sheetVerifyStamp) — the
   stamp dies with the next edit (a connectivity hash), and save_module (23-…) asks for it. */

/* ---- connectivity hash of one sheet: parts + params + nets, not positions ---- */
function sheetHash(sch){
  const out=[];
  sch.components.filter(c=>c.type!=="JUNCTION").map(c=>c.id+"|"+c.type+"|"+JSON.stringify(c.params||{})).sort().forEach(x=>out.push(x));
  try{ const seen=new Set(); sch.wires.forEach(w=>{ if(seen.has(w.id)) return; const ids=[...netWires(sch,w)]; ids.forEach(i=>seen.add(i));
    const ends=new Set(); ids.forEach(i=>{ const x=sch.wires.find(q=>q.id===i); if(!x) return;
      [x.from,x.to].forEach(e=>{ const c=comp(e.cid,sch); if(c&&c.type!=="JUNCTION") ends.add(e.cid+"."+e.pid); }); });
    out.push("net:"+[...ends].sort().join(",")); }); }catch(_){}
  const str=out.join("\n"); let h=2166136261>>>0;
  for(let i=0;i<str.length;i++){ h^=str.charCodeAt(i); h=Math.imul(h,16777619)>>>0; }
  return h.toString(16)+"-"+str.length;
}
function sheetVerifyStamp(sch, how){ sch.verified={how, hash:sheetHash(sch), at:Date.now()}; }
function sheetVerified(sch){ return !!(sch && sch.verified && sch.verified.hash===sheetHash(sch)); }

/* ---- small intent builders ---- */
function ptIntent(module){
  const C=[], N=[]; let g=0;
  const it={module, components:C, nets:N,
    IN:(name)=>{ C.push({id:"i_"+name, type:"IN", name}); return "i_"+name; },
    OUT:(name, from)=>{ C.push({id:"o_"+name, type:"OUT", name}); N.push({from, to:"o_"+name}); },
    G:(type, ins)=>{ const id=type.toLowerCase()+(g++); C.push({id, type}); ins.forEach(s=>N.push({from:s, to:id})); return id; },
    X:(type, extra)=>{ const id=type.toLowerCase()+(g++); C.push(Object.assign({id, type}, extra||{})); return id; },
    W:(from, to)=>N.push({from, to}) };
  return it;
}
const ptBits=(v,i)=>(v>>>i)&1;
/* a combinational part as a truth table over per-bit input names (first = MSB of the row) */
function ptFromTable(module, inNames, outNames, fn){
  const rows={}; outNames.forEach(o=>rows[o]=[]);
  const n=inNames.length;
  for(let r=0;r<(1<<n);r++){ const v={}; inNames.forEach((nm,i)=>v[nm]=(r>>(n-1-i))&1);
    const o=fn(v); outNames.forEach(nm=>rows[nm].push(o[nm]==null?"x":String(o[nm]?1:0))); }
  const t=ttToIntent(inNames, outNames, rows, module);
  if(t.error) throw new Error(t.error);
  return t.intent;
}
/* per-bit names MSB first: bitNames("a",3) → a2 a1 a0 */
