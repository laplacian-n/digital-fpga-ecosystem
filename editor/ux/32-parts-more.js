/* minimised sum of products over nets. vars[i] = {p:net, n:net|null} is bit i of the minterm index;
   a missing complement gets one NOT (cached). Gates wider than 8 inputs become a tree. */
function ptGate(t, type, ins){
  if(ins.length===1) return ins[0];
  if(ins.length<=8) return t.G(type, ins);
  const parts=[]; for(let i=0;i<ins.length;i+=8) parts.push(ptGate(t, type, ins.slice(i,i+8)));
  return ptGate(t, type, parts);
}
function ptSop(t, vars, ones, dc){
  const res=qmMinimize(ones, dc||[], vars.length);
  if(res.const1) return t.X("VCC");
  if(res.const0 || !res.terms.length) return t.X("GND");
  const lit=l=>{ const v=vars[l.v]; if(!l.neg) return v.p; if(!v.n) v.n=t.G("NOT",[v.p]); return v.n; };
  return ptGate(t, "OR", res.terms.map(ls=>ptGate(t, "AND", ls.map(lit))));
}
