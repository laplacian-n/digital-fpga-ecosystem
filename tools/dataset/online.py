#!/usr/bin/env python3
"""Open datasets worth mixing in, cleaned down to the rows that are good and useful here.

  pip install pyarrow
  python3 tools/dataset/online.py --cache /tmp/hf --out out/ [--thai 1500] [--tools 400]

What was looked at (read, not just downloaded) and what is kept:
  airesearch/wangchanx-seed-free-synthetic-instruct-thai-120k   MIT          KEPT (Thai fluency mix)
      synthetic, each row rated by a judge model. Kept: rating ≥ 8.2, grounded types first
      (summarization / QA over a given context), brainstorming; no "ครับ/ค่ะ" (both genders at once),
      no repeated-word glitches, mostly Thai, 40–2000 chars. Open conversation rows state made-up
      facts ("ไหว้ครูทุกวันศุกร์ที่ 16 มิถุนายน") — taken only when they carry a context.
  NousResearch/hermes-function-calling-v1 (func_calling, singleturn)   Apache-2.0   KEPT (general tool use)
      keeps tool calling general while the app's own data is narrow; converted to OpenAI tool_calls.
  airesearch/WangchanThaiInstruct      NOT kept: 84 % CC-BY-NC, and retail / medical / finance / legal.
  hdl2v/vhdl-dataset, rtl-llm/*        NOT kept: VHDL→Verilog translation / raw GitHub HDL (mixed
      licences, pre-training material, not what the app's model does — VHDL is generated by the app).
  Salesforce/xlam-function-calling-60k NOT kept: gated; hermes covers the same skill.
"""
import argparse
import hashlib
import json
import os
import random
import re
import urllib.request

HF = "https://huggingface.co/api/datasets"
SOURCES = {
    "wx0": f"{HF}/airesearch/wangchanx-seed-free-synthetic-instruct-thai-120k/parquet/default/train/0.parquet",
    "wx1": f"{HF}/airesearch/wangchanx-seed-free-synthetic-instruct-thai-120k/parquet/default/train/1.parquet",
    "hfc": f"{HF}/NousResearch/hermes-function-calling-v1/parquet/func_calling/train/0.parquet",
    "hfc1": f"{HF}/NousResearch/hermes-function-calling-v1/parquet/func_calling_singleturn/train/0.parquet",
}
THAI = re.compile(r"[฀-๿]")
LETTER = re.compile(r"[A-Za-z฀-๿]")
STEM = re.compile(r"วงจร|ดิจิทัล|ตรรกะ|ไฟฟ้า|เลขฐาน|คอมพิวเตอร์|ทรานซิสเตอร์|สัญญาณ|โปรแกรม|คณิต|ฟิสิกส์|วิศวกรรม")
CREATIVE = re.compile(r"สไตล์|Shakespeare|เชกสเปียร์|กลอน|บทกวี|ร้อยกรอง|โคลง|แร็พ|ฉันท์|เป็นกัปตัน|สวมบทบาท")   # comes out garbled
BAD = re.compile(r"ครับ/ค่ะ|ค่ะ/ครับ|ChatGPT|OpenAI|GPT-\d|ในฐานะ(?:โมเดล|AI)|As an AI")


def fetch(cache, key):
    path = os.path.join(cache, key + ".parquet")
    if not os.path.exists(path):
        os.makedirs(cache, exist_ok=True)
        urllib.request.urlretrieve(SOURCES[key], path + ".part")
        os.replace(path + ".part", path)
    import pyarrow.parquet as pq
    return pq.read_table(path).to_pylist()


def glitchy(s):
    """Repeated words / phrases a generator stuttered on."""
    if re.search(r"(\S{2,})\1{2,}", s):                      # บรรดาบรรดาบรรดา
        return True
    words = s.split()
    if len(words) > 20 and len(set(words)) / len(words) < 0.35:
        return True
    grams = [s[i:i + 12] for i in range(0, max(0, len(s) - 12), 6)]
    return len(grams) > 10 and max(grams.count(g) for g in set(grams)) >= 4


def thai_ratio(s):
    L = LETTER.findall(s)
    return len(THAI.findall(s)) / len(L) if L else 0


def clean_thai(rows, n, rng):
    keep = []
    for r in rows:
        ins, ctx, out, typ = (r["instruction"] or "").strip(), (r["context"] or "").strip(), (r["output"] or "").strip(), r["type"]
        if (r["rating"] or 0) < 8.2 or not ins or len(ins) < 10 or not (40 <= len(out) <= 2000) or len(ctx) > 1500:
            continue
        if typ == "conversation" and not ctx:                    # free-standing claims: too many made-up facts
            continue
        if typ == "multiple_choice":
            continue
        if CREATIVE.search(ins) or BAD.search(ins + out) or glitchy(out) or thai_ratio(out) < 0.6 or thai_ratio(ins) < 0.4:
            continue
        user = ins + ("\n\n" + ctx if ctx else "")
        grounded = bool(ctx) and typ in ("summarization", "question_answering")
        keep.append({"user": user, "out": out, "typ": typ, "rating": r["rating"],
                     # grounded rows (the answer is in the given text) first; STEM only breaks ties among
                     # them — as a keyword alone it pulled in a garbled letter that happened to say "วงจร"
                     "w": (2 if grounded else 0) + (1 if grounded and STEM.search(ins + out) else 0)})
    # dedupe by instruction
    seen, uniq = set(), []
    for k in keep:
        h = hashlib.sha1(k["user"][:200].encode()).hexdigest()
        if h not in seen:
            seen.add(h)
            uniq.append(k)
    rng.shuffle(uniq)
    uniq.sort(key=lambda k: -k["w"])
    g = [k for k in uniq if k["w"] >= 2]
    rest = [k for k in uniq if k["w"] < 2]
    pick = g[:int(n * 0.75)]                                  # ≈ 3/4 grounded, 1/4 creative / open
    pick += rest[:n - len(pick)]
    rng.shuffle(pick)
    return [{"id": f"thai-{i:05d}", "cat": "general_thai", "source": "airesearch/wangchanx-seed-free-synthetic-instruct-thai-120k",
             "license": "MIT", "messages": [{"role": "user", "content": k["user"]}, {"role": "assistant", "content": k["out"]}],
             "meta": {"type": k["typ"], "rating": k["rating"]}} for i, k in enumerate(pick)], len(uniq)


TOOL_CALL = re.compile(r"<tool_call>\s*(.*?)\s*</tool_call>", re.S)
TOOL_RESP = re.compile(r"<tool_response>\s*(.*?)\s*</tool_response>", re.S)


def convert_hermes(r, k):
    """Hermes XML-in-text turns → OpenAI messages with tool_calls / tool results. None if anything is off."""
    try:
        tools = json.loads(r["tools"]) if isinstance(r["tools"], str) else r["tools"]
    except Exception:
        return None
    if not tools or len(tools) > 8:
        return None
    msgs, pending, n = [], [], 0
    for m in r["conversations"]:
        role, val = m["from"], (m["value"] or "").strip()
        if role == "system":
            continue                                            # the tool list goes in `tools`, not a prompt
        if role == "human":
            msgs.append({"role": "user", "content": val})
        elif role == "gpt":
            calls = TOOL_CALL.findall(val)
            text = TOOL_CALL.sub("", val).strip()
            tc = []
            for c in calls:
                try:
                    j = json.loads(c)
                except Exception:
                    try:
                        import ast
                        j = ast.literal_eval(c)
                    except Exception:
                        return None
                if "name" not in j:
                    return None
                n += 1
                tc.append({"id": f"call_{n}", "type": "function",
                           "function": {"name": j["name"], "arguments": json.dumps(j.get("arguments", {}), ensure_ascii=False)}})
            msg = {"role": "assistant", "content": text}
            if tc:
                msg["tool_calls"] = tc
                pending = [c["id"] for c in tc]
            msgs.append(msg)
        elif role == "tool":
            resps = TOOL_RESP.findall(val) or [val]
            for i, x in enumerate(resps):
                if not pending:
                    return None
                msgs.append({"role": "tool", "tool_call_id": pending.pop(0), "content": x})
        else:
            return None
    if not msgs or msgs[-1]["role"] != "assistant" or not any(m.get("tool_calls") for m in msgs):
        return None
    names = {t["function"]["name"] for t in tools if "function" in t}
    if any(c["function"]["name"] not in names for m in msgs for c in m.get("tool_calls", [])):
        return None
    return {"id": f"tools-{k:05d}", "cat": "general_tools", "source": "NousResearch/hermes-function-calling-v1",
            "license": "Apache-2.0", "tools": tools, "messages": msgs, "meta": {"category": r.get("category")}}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--cache", default="/tmp/hf")
    ap.add_argument("--out", default="out")
    ap.add_argument("--thai", type=int, default=1500)
    ap.add_argument("--tools", type=int, default=400)
    ap.add_argument("--seed", type=int, default=7)
    a = ap.parse_args()
    rng = random.Random(a.seed)
    os.makedirs(a.out, exist_ok=True)
    stats = {}
    rows = fetch(a.cache, "wx0") + fetch(a.cache, "wx1")
    thai, pool = clean_thai(rows, a.thai, rng)
    stats["general_thai"] = {"source_rows": len(rows), "passed_filters": pool, "kept": len(thai)}
    conv = []
    for key in ("hfc", "hfc1"):
        for r in fetch(a.cache, key):
            c = convert_hermes(r, len(conv))
            if c:
                conv.append(c)
    seen, uniq = set(), []
    for c in conv:
        h = hashlib.sha1(c["messages"][0]["content"][:300].encode()).hexdigest()
        if h not in seen:
            seen.add(h)
            uniq.append(c)
    rng.shuffle(uniq)
    tools = uniq[:a.tools]
    for i, c in enumerate(tools):
        c["id"] = f"tools-{i:05d}"
    stats["general_tools"] = {"converted": len(conv), "unique": len(uniq), "kept": len(tools)}
    for name, data in (("general_thai.jsonl", thai), ("general_tools.jsonl", tools)):
        with open(os.path.join(a.out, name), "w", encoding="utf-8") as f:
            for r in data:
                f.write(json.dumps(r, ensure_ascii=False) + "\n")
    print(json.dumps(stats, ensure_ascii=False, indent=1))


if __name__ == "__main__":
    main()
